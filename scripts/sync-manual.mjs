/**
 * Regenerate src/content/operations-manual.ts from the repo manual.
 *
 * The manual's single source of truth is docs/product_operations_manual.md at
 * the repository root (shared with the ops-manual skill). The admin app is
 * deployed on its own (Vercel builds only this directory), so the content has
 * to be bundled — this script copies it and extracts the table of contents so
 * the backend page never renders a stale hand-copied version.
 *
 * Run after editing the manual:  pnpm manual:sync
 * Drift is caught by src/content/operations-manual.test.ts.
 */
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const adminRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const source = resolve(adminRoot, '../docs/product_operations_manual.md');
const target = resolve(adminRoot, 'src/content/operations-manual.ts');

const markdown = readFileSync(source, 'utf-8');

/** Level-2/3 headings become the in-page table of contents. */
const toc = [];
let inFence = false;
for (const line of markdown.split('\n')) {
  if (line.trimStart().startsWith('```')) inFence = !inFence;
  if (inFence) continue;
  const heading = /^(#{2,3})\s+(.+?)\s*$/.exec(line);
  if (heading) toc.push({ level: heading[1].length, title: heading[2] });
}

const updatedAt =
  /^>\s*更新：(\d{4}-\d{2}-\d{2})/m.exec(markdown)?.[1] ?? null;

const output = `// AUTO-GENERATED by scripts/sync-manual.mjs — do not edit by hand.
// Source of truth: docs/product_operations_manual.md
// Regenerate: pnpm manual:sync
/* eslint-disable */

export const MANUAL_MARKDOWN = ${JSON.stringify(markdown)};

export const MANUAL_UPDATED_AT: string | null = ${JSON.stringify(updatedAt)};

export const MANUAL_TOC: { level: number; title: string }[] = ${JSON.stringify(toc, null, 2)};
`;

mkdirSync(dirname(target), { recursive: true });
writeFileSync(target, output);
console.log(
  `manual synced: ${markdown.length} chars, ${toc.length} headings -> src/content/operations-manual.ts`
);
